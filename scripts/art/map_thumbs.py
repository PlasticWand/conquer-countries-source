"""Pack the imported maps' thumbnails into atlas pages for the map picker.

Usage, from the project root (after scripts/list-imported-maps.py):
    python -I scripts/art/map_thumbs.py [referenceRoot]

Each map's resources/maps/<dir>/thumbnail.webp (OpenFront, CC BY-SA 4.0, credit
"OpenFront") is fitted into a 256x160 cell, keeping its transparency. Pages are
1024x960 (4x6 cells). Writes assets/ui/map-thumbs-<n>.png and
src/client/Ui/MapThumbs.luau (folder -> page and cell). Upload the pages with
scripts/upload_images.py --openfront and put the ids in MapThumbs.PAGES.
"""
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
REF = Path(sys.argv[1] if len(sys.argv) > 1 else "../reference/openfront-v0.35.2")
CELL_W, CELL_H = 256, 160
COLS, ROWS = 4, 6


def source_dir(init_text: str) -> str:
    return re.search(r'source = "openfront-v0\.35\.2/([^"]+)"', init_text).group(1)


def main() -> None:
    maps = []
    for init in sorted((ROOT / "src" / "maps").glob("*/init.luau")):
        maps.append((init.parent.name, source_dir(init.read_text(encoding="utf-8"))))
    per_page = COLS * ROWS
    pages = []
    cells = {}
    for i, (folder, src) in enumerate(maps):
        page, slot = divmod(i, per_page)
        if page == len(pages):
            pages.append(Image.new("RGBA", (COLS * CELL_W, ROWS * CELL_H), (0, 0, 0, 0)))
        thumb = Image.open(REF / "resources" / "maps" / src / "thumbnail.webp").convert("RGBA")
        thumb.thumbnail((CELL_W - 8, CELL_H - 8), Image.LANCZOS)
        col, row = slot % COLS, slot // COLS
        x = col * CELL_W + (CELL_W - thumb.width) // 2
        y = row * CELL_H + (CELL_H - thumb.height) // 2
        pages[page].alpha_composite(thumb, (x, y))
        cells[folder] = (page + 1, col, row)
    for n, img in enumerate(pages, 1):
        img.save(ROOT / "assets" / "ui" / f"map-thumbs-{n}.png")
    existing = ROOT / "src" / "client" / "Ui" / "MapThumbs.luau"
    ids = re.findall(r'"(rbxassetid://\d+)"', existing.read_text(encoding="utf-8")) if existing.exists() else []
    lines = [
        "--!strict",
        "-- Generated by scripts/art/map_thumbs.py; PAGES are the uploaded ids (kept",
        "-- across regenerations; re-upload changed pages). OpenFront map thumbnails,",
        "-- CC BY-SA 4.0, credit \"OpenFront\".",
        "return {",
        f"\tcellW = {CELL_W},",
        f"\tcellH = {CELL_H},",
        "\tPAGES = { " + ", ".join(f'"{ids[i]}"' if i < len(ids) else '""' for i in range(len(pages))) + " },",
        "\tcells = {",
    ]
    for folder, (page, col, row) in cells.items():
        lines.append(f"\t\t{folder} = {{ {page}, {col}, {row} }},")
    lines += ["\t},", "}", ""]
    existing.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(maps)} thumbnails on {len(pages)} page(s)")


if __name__ == "__main__":
    main()
