"""Draw the imported maps as relief maps for the map picker (Bruno's
reference, docs/design/dossier-ui/mappicker-reference.png).

Usage, from the project root:
    python scripts/art/relief_maps.py [referenceRoot]

Reads each map's resources/maps/<dir>/map4x.bin (OpenFront, CC BY-SA 4.0,
credit "OpenFront"): one terrain byte per tile, land bit 7, ocean bit 5,
magnitude bits 0..4 (31 is impassable). Draws a navy sea with a faint grid
and land from green lowlands through tan hills to white peaks, lit from the
north-west, fitted into a 256x160 cell. Pages are 1024x960 (4x6 cells).
Writes assets/ui/relief-maps-<n>.png and src/client/Ui/ReliefMaps.luau
(folder -> page and cell). Upload the pages with scripts/upload_images.py
--openfront and put the ids in ReliefMaps.PAGES.
"""
import json
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
REF = Path(sys.argv[1] if len(sys.argv) > 1 else "../reference/openfront-v0.35.2")
CELL_W, CELL_H = 256, 160
COLS, ROWS = 4, 6

SEA = (24, 42, 74)
GRID = (52, 72, 104)
# Land colour by height (0..1).
RAMP = [
    (0.00, (124, 160, 92)),
    (0.30, (156, 182, 110)),
    (0.55, (196, 190, 140)),
    (0.80, (226, 222, 204)),
    (1.00, (250, 250, 248)),
]


def source_dir(init_text: str) -> str:
    return re.search(r'source = "openfront-v0\.35\.2/([^"]+)"', init_text).group(1)


def ramp(t: float):
    for (t0, c0), (t1, c1) in zip(RAMP, RAMP[1:]):
        if t <= t1:
            f = (t - t0) / (t1 - t0)
            return tuple(round(c0[i] + (c1[i] - c0[i]) * f) for i in range(3))
    return RAMP[-1][1]


def draw(src: str) -> Image.Image:
    folder = REF / "resources" / "maps" / src
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    w, h = manifest["map4x"]["width"], manifest["map4x"]["height"]
    data = (folder / "map4x.bin").read_bytes()[: w * h]
    height = Image.new("L", (w, h))
    land = Image.new("L", (w, h))
    hp, lp = height.load(), land.load()
    for y in range(h):
        row = y * w
        for x in range(w):
            t = data[row + x]
            if t & 0x80 and (t & 0x1F) != 31:
                hp[x, y] = round((t & 0x1F) / 30 * 255)
                lp[x, y] = 255
    # Fit inside the cell, 2x oversampled.
    scale = min(CELL_W * 2 / w, CELL_H * 2 / h)
    ow, oh = max(1, round(w * scale)), max(1, round(h * scale))
    height = height.resize((ow, oh), Image.BILINEAR).filter(ImageFilter.GaussianBlur(1))
    land = land.resize((ow, oh), Image.BILINEAR).filter(ImageFilter.GaussianBlur(1.2)).point(lambda v: 255 if v > 110 else 0)
    hp, lp = height.load(), land.load()
    img = Image.new("RGB", (ow, oh), SEA)
    px = img.load()
    for y in range(oh):
        for x in range(ow):
            if not lp[x, y]:
                continue
            t = hp[x, y] / 255
            r, g, b = ramp(min(1.0, t * 1.25))
            # Hill shade: light from the north-west.
            nw = hp[max(0, x - 1), max(0, y - 1)]
            se = hp[min(ow - 1, x + 1), min(oh - 1, y + 1)]
            s = max(-40, min(40, (nw - se) * 0.9))
            px[x, y] = (max(0, min(255, round(r + s))), max(0, min(255, round(g + s))), max(0, min(255, round(b + s))))
    cell = Image.new("RGB", (CELL_W * 2, CELL_H * 2), SEA)
    grid = ImageDraw.Draw(cell)
    for gx in range(0, CELL_W * 2, 40):
        grid.line([(gx, 0), (gx, CELL_H * 2)], fill=GRID, width=1)
    for gy in range(0, CELL_H * 2, 40):
        grid.line([(0, gy), (CELL_W * 2, gy)], fill=GRID, width=1)
    ox, oy = (CELL_W * 2 - ow) // 2, (CELL_H * 2 - oh) // 2
    cell.paste(img, (ox, oy), land)
    return cell.resize((CELL_W, CELL_H), Image.LANCZOS)


def main() -> None:
    maps = []
    for init in sorted((ROOT / "src" / "maps").glob("*/init.luau")):
        maps.append((init.parent.name, source_dir(init.read_text(encoding="utf-8"))))
    per_page = COLS * ROWS
    pages, cells = [], {}
    for i, (folder, src) in enumerate(maps):
        page, slot = divmod(i, per_page)
        if page == len(pages):
            pages.append(Image.new("RGB", (COLS * CELL_W, ROWS * CELL_H), SEA))
        col, row = slot % COLS, slot // COLS
        pages[page].paste(draw(src), (col * CELL_W, row * CELL_H))
        cells[folder] = (page + 1, col, row)
        print(folder, src)
    out = ROOT / "assets" / "ui"
    for n, p in enumerate(pages, 1):
        p.save(out / f"relief-maps-{n}.png")
    module = ROOT / "src" / "client" / "Ui" / "ReliefMaps.luau"
    old = module.read_text(encoding="utf-8") if module.exists() else ""
    kept = re.search(r"PAGES = \{([^}]*)\}", old)
    lines = [
        "--!strict",
        "-- Generated by scripts/art/relief_maps.py: the maps as relief maps for the",
        "-- map picker. PAGES are the uploaded ids (kept across regenerations;",
        "-- re-upload changed pages). Drawn from OpenFront map data, CC BY-SA 4.0,",
        '-- credit "OpenFront".',
        "return {",
        f"\tcellW = {CELL_W},",
        f"\tcellH = {CELL_H},",
        f"\tPAGES = {{{kept.group(1) if kept else ''}}},",
        "\tcells = {",
    ]
    for folder, (page, col, row) in cells.items():
        lines.append(f"\t\t{folder} = {{ {page}, {col}, {row} }},")
    lines += ["\t},", "}", ""]
    module.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
