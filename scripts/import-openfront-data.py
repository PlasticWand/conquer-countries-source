# Generates src/shared/OpenFront/Data/{MapInfo,TribeNameThemes,QuickChat,LangEn}.luau
# from OpenFront v0.35.2's map table (packages/engine-api/src/game/Maps.gen.ts),
# resources/tribeNameThemes.json, resources/QuickChat.json and the HUD
# sections of resources/lang/en.json (all CC BY-SA 4.0, credit "OpenFront").
# QuickChat.json and en.json are read straight from the pinned clone.
#
# The input JSON is dumped by OpenFront's own code, in the runnable copy:
#   cd ../reference/openfront-run
#   OUT=<file>.json npx vitest run tests/conquest/DumpData.test.ts
# then:
#   python -I scripts/import-openfront-data.py <file>.json
import json
import sys

RESOURCES = "../reference/openfront-v0.35.2/resources/"
QUICK_CHAT = RESOURCES + "QuickChat.json"
# The en.json sections the in-match HUD and the menus use.
LANG_SECTIONS = [
    "events_display", "chat", "player_panel", "unit_type", "build_menu", "emoji_table",
    "radial_menu", "control_panel", "leaderboard", "win_modal", "relation", "heads_up_message",
    # 2026-10-24 menus: map picker, solo setup, how to play, settings, timers.
    "map", "map_categories", "difficulty", "help_modal", "user_setting", "game_mode",
    "public_lobby", "single_modal", "send_gold_modal", "send_troops_modal", "spawn_timer",
    "game_timer", "team_colors", "doomsday_clock",
]

HEADER = """--!strict
-- Generated by scripts/import-openfront-data.py from OpenFront v0.35.2 ({src}).
-- © OpenFront and Contributors. {licence} Do not edit; regenerate.
"""


def lua(value, indent=0):
    pad = "\t" * indent
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        if not value:
            return "{}"
        if all(not isinstance(v, (dict, list)) for v in value):
            return "{ " + ", ".join(lua(v) for v in value) + " }"
        # Entries differ in shape; cast each so strict mode accepts the list.
        inner = ",\n".join(pad + "\t" + lua(v, indent + 1) + " :: any" for v in value)
        return "{\n" + inner + ",\n" + pad + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        parts = []
        for k, v in value.items():
            key = k if k.isidentifier() else "[" + json.dumps(k) + "]"
            parts.append(pad + "\t" + key + " = " + lua(v, indent + 1))
        return "{\n" + ",\n".join(parts) + ",\n" + pad + "}"
    raise TypeError(type(value))


def write_lang(out):
    en = json.load(open(RESOURCES + "lang/en.json", encoding="utf-8"))
    with open(out + "LangEn.luau", "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(src="resources/lang/en.json, HUD and menu sections", licence="CC BY-SA 4.0."))
        f.write('-- Look strings up with OpenFront/Lang.t("section.key", params).\n')
        f.write("return " + lua({k: en[k] for k in LANG_SECTIONS}) + "\n")


def main():
    out = "src/shared/OpenFront/Data/"
    # --lang-only: just LangEn, straight from en.json (no dump needed).
    if sys.argv[1:] == ["--lang-only"]:
        write_lang(out)
        print("wrote", len(LANG_SECTIONS), "lang sections")
        return
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    with open(out + "TribeNameThemes.luau", "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(src="resources/tribeNameThemes.json", licence="CC BY-SA 4.0."))
        f.write("return " + lua(data["themes"]) + "\n")
    with open(out + "MapInfo.luau", "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(src="packages/engine-api/src/game/Maps.gen.ts", licence="AGPL-3.0."))
        f.write("-- One entry per map, in OpenFront's order. `type` is the GameMapType value.\n")
        f.write("return " + lua(data["maps"]) + "\n")
    chat = json.load(open(sys.argv[2] if len(sys.argv) > 2 else QUICK_CHAT, encoding="utf-8"))
    categories = [{"name": name, "entries": entries} for name, entries in chat.items()]
    with open(out + "QuickChat.luau", "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(src="resources/QuickChat.json", licence="CC BY-SA 4.0."))
        f.write(
            "-- The quick-chat messages: categories in order, each entry with its key and\n"
            '-- whether it names a target player. The wire key is "category.key".\n\n'
            "local QuickChat = {}\n\n"
            "QuickChat.categories = " + lua(categories) + "\n\n"
            '-- "category.key" -> requiresPlayer\n'
            "QuickChat.keys = {} :: { [string]: boolean }\n"
            "for _, c in QuickChat.categories do\n"
            "\tfor _, e in c.entries do\n"
            "\t\tQuickChat.keys[`{c.name}.{e.key}`] = e.requiresPlayer\n"
            "\tend\n"
            "end\n\n"
            "return QuickChat\n"
        )
    write_lang(out)
    print("wrote", len(data["maps"]), "maps,", len(data["themes"]), "themes,", len(categories), "chat categories,", len(LANG_SECTIONS), "lang sections")


main()
