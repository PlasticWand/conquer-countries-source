"""Write src/shared/OpenFront/Data/ImportedMaps.luau: the maps in src/maps/ with
their full-size dimensions, so the client's map picker knows what can be played
(clients only receive the map in play).

Usage, from the project root, after importing maps:
    python -I scripts/list-imported-maps.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    rows = []
    for init in sorted((ROOT / "src" / "maps").glob("*/init.luau")):
        text = init.read_text(encoding="utf-8")
        ident = re.search(r'\n\tid = "([^"]+)"', text).group(1)
        size = re.search(r"\n\t\tmap = \{\s*width = (\d+),\s*height = (\d+),\s*numLandTiles = (\d+),", text)
        rows.append((init.parent.name, ident, int(size.group(1)), int(size.group(2)), int(size.group(3))))
    lines = [
        "--!strict",
        "-- Generated by scripts/list-imported-maps.py. Do not edit; regenerate.",
        "-- The OpenFront maps imported into this place (src/maps -> ServerStorage.OpenFrontMaps):",
        "-- folder name, MapInfo id, and the full-size map's width, height and land tiles.",
        "return {",
    ]
    for folder, ident, w, h, land in rows:
        lines.append(f'\t{{ folder = "{folder}", id = "{ident}", width = {w}, height = {h}, landTiles = {land} }},')
    lines += ["}", ""]
    out = ROOT / "src" / "shared" / "OpenFront" / "Data" / "ImportedMaps.luau"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(rows)} maps:", ", ".join(r[0] for r in rows))


if __name__ == "__main__":
    main()
