"""Derive an upload-free 64px icon atlas from OpenFront's open resource atlases.

Artwork: OpenFront and Contributors, CC BY-SA 4.0. No proprietary/CDN art.
Requires Pillow; executes no code in the reference checkout.
"""
from pathlib import Path
from PIL import Image, ImageFilter
import base64, hashlib, json, struct
from compression import zstd

REF=Path('../reference/openfront-v0.35.2')
OUT=Path('src/client/Map/OpenFront')
sources=['resources/atlases/status-atlas.png','resources/atlases/status-atlas-meta.json',
         'resources/atlases/emoji-atlas.png','resources/atlases/emoji-atlas-meta.json']
hashes={p:hashlib.sha256((REF/p).read_bytes()).hexdigest() for p in sources}
status=Image.open(REF/sources[0]).convert('RGBA')
emoji=Image.open(REF/sources[2]).convert('RGBA')
meta=json.loads((REF/sources[3]).read_text(encoding='utf-8'))
atlas=Image.new('RGBA',(640,448))
for i in range(10):
    x,y=i%3*256,i//3*256
    cell=status.crop((x,y,x+256,y+256))
    # Source alliance/faded cells get a dark alpha dilation. Native GUI
    # filtering approximates the shader's eight bilinear ring samples.
    if i in (3,9):
        rim=cell.getchannel('A').filter(ImageFilter.MaxFilter(13))
        under=Image.new('RGBA',cell.size,(0,0,0,0)); under.putalpha(rim)
        under.alpha_composite(cell); cell=under
    atlas.paste(cell.resize((64,64),Image.Resampling.LANCZOS),(i*64,0))
for i in range(60):
    x,y=i%10*128,i//10*128
    atlas.paste(emoji.crop((x,y,x+128,y+128)).resize((64,64),Image.Resampling.LANCZOS),(i%10*64,64+i//10*64))
raw=bytearray(atlas.tobytes())
for i in range(0,len(raw),4):
    if raw[i+3]==0: raw[i:i+4]=b'\0\0\0\0'
Image.frombytes('RGBA',atlas.size,bytes(raw)).save('tests/fixtures/OpenFrontStatusAtlas.png')
compressed=zstd.compress(raw,level=19)
assert zstd.decompress(compressed)==raw
encoded=base64.b64encode(compressed).decode('ascii')
header='--!strict\n-- Artwork: OpenFront resources/atlases, CC BY-SA 4.0. Credit: OpenFront and Contributors.\n-- Generated by tests/generate-openfront-status-art.py; resized, alliance outline baked.\n'
parts=[]
for i,start in enumerate(range(0,len(encoded),96000)):
    name=f'StatusAtlasData{i:02}'
    (OUT/f'{name}.luau').write_text(header+'return [=['+encoded[start:start+96000]+']=]\n',encoding='utf-8')
    parts.append(f'require(script.Parent.{name})')
for file in OUT.glob('StatusAtlasData[0-9][0-9].luau'):
    if int(file.stem[-2:])>=len(parts):
        assert file.resolve().is_relative_to(OUT.resolve())
        assert file.read_text(encoding='utf-8').startswith(header)
        file.unlink()
(OUT/'StatusAtlasData.luau').write_text(header+'return table.concat({'+','.join(parts)+'})\n',encoding='utf-8')
lookup={key:value for key,value in meta['emojis'].items()}
lookup_lua='--!strict\n-- OpenFront resources/atlases/emoji-atlas-meta.json, CC BY-SA 4.0. Credit: OpenFront.\nreturn {\n'+''.join(f'\t[{json.dumps(k,ensure_ascii=False)}] = {v},\n' for k,v in lookup.items())+'}\n'
(OUT/'StatusEmojiLookup.luau').write_text(lookup_lua,encoding='utf-8')
samples=[]
for n in range(160):
    x=(n*173+31)%640; y=(n*113+53)%448
    samples.append([x,y,struct.unpack_from('<I',raw,(y*640+x)*4)[0]])
record={'source':'OpenFront v0.35.2 resources only','hashes':hashes,'width':640,'height':448,
        'rgbaSha256':hashlib.sha256(raw).hexdigest(),'rgbaBytes':len(raw),'compressedBytes':len(compressed),'compression':'Zstd',
        'encodedCharacters':len(encoded),'parts':len(parts),'samples':samples,'emojiLookup':lookup}
Path('tests/fixtures/OpenFrontStatusArt.json').write_text(json.dumps(record,indent=2,ensure_ascii=False),encoding='utf-8')
print(json.dumps({k:v for k,v in record.items() if k not in ('samples','emojiLookup','hashes')}))
